const fs=require('node:fs');
const ts=require('../node_modules/typescript');
const assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../src/productOffers.ts'),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};new Function('exports','module',output)(mod.exports,mod);
const {packKey,equivalentProduct,offerForPack}=mod.exports;
const base={id:'test-a',shopId:'shop-a',name:'Test rice',brand:'Test brand',categorySlug:'grocery-kirana',unit:'500 g',price:28,stock:3};
const other={...base,id:'test-b',shopId:'shop-b',unit:'0.5 kg',price:32};
assert.equal(packKey('0.5 kg'),packKey('500 g'));
assert.equal(packKey('1 L'),packKey('1000 ml'));
assert.notEqual(packKey('200'),packKey('200 g'));
assert.equal(equivalentProduct(base,other),true);
assert.equal(equivalentProduct(base,{...other,brand:'Different brand'}),false);
assert.equal(equivalentProduct({...base,brand:undefined},{...other,brand:undefined}),false);
assert.equal(equivalentProduct({...base,attributes:[{label:'GTIN',value:'123'}]},{...other,attributes:[{label:'GTIN',value:'456'}]}),false);
assert.equal(offerForPack(other,packKey('500 g')).price,32);
assert.equal(offerForPack(other,packKey('1 kg')),null);
const variant={...other,variants:[{id:'other-1kg',label:'1 kg',price:60,stock:2}]};
const offer=offerForPack(variant,packKey('1000 g'));
assert.equal(offer.line.id,'test-b:other-1kg');
assert.equal(offer.line.productId,'test-b');
assert.equal(offer.line.variantId,'other-1kg');
assert.equal(offer.line.shopId,'shop-b');
assert.equal(offer.line.price,60);
assert.equal(offer.line.stock,2);
assert.equal(offerForPack({...variant,mrp:99},packKey('1 kg')).mrp,undefined);
assert.equal(offerForPack({...other,mrp:40,variants:[{id:'base-pack',label:'500 g',price:32,stock:2}]},packKey('500 g')).mrp,40);
console.log('PASS: conservative product identity, barcode conflicts, pack equivalence, mismatched packs, selected seller/variant cart payload.');
